// Writes a static, crawlable list of every event into each demo page, so
// search engines and link previews that don't run JavaScript still see the
// timeline's content. The list is built from the same data/en/*.js files the
// page imports, in the same order.
//
// Run after changing any demo data:  node scripts/build-event-lists.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- event-list:start (generated by scripts/build-event-lists.mjs, do not edit by hand) -->';
const END = '<!-- event-list:end -->';
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const DATE = /^(-?\d+)(?:-(\d{2}))?(?:-(\d{2}))?$/;

const escapeHtml = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function parse(value) {
  if (typeof value === 'number') return { y: value };
  const m = DATE.exec(value);
  if (!m) throw new Error(`unexpected date format: ${value}`);
  return { y: Number(m[1]), mo: m[2] && Number(m[2]), d: m[3] && Number(m[3]) };
}

// Same style as Chroniko's formatDate: 2070 BCE, Jan 1739, 31 Mar 1596.
function formatDate(value) {
  const { y, mo, d } = parse(value);
  return [d, mo && MONTHS[mo - 1], y < 0 ? `${-y} BCE` : y].filter(Boolean).join(' ');
}

function sortKey(value) {
  const { y, mo = 1, d = 1 } = parse(value);
  return y + (mo - 1) / 12 + (d - 1) / 372;
}

const capitalize = (s) => s.charAt(0).toUpperCase() + s.slice(1);

async function build(demo) {
  const pagePath = path.join(root, demo, 'index.html');
  const html = fs.readFileSync(pagePath, 'utf8');

  // Load the English data files in the order the page imports them.
  const files = [...html.matchAll(/from '\.\/data\/en\/([^']+)'/g)].map((m) => m[1]);
  if (!files.length) throw new Error(`${demo}: no ./data/en/ imports found`);
  let events = [];
  for (const file of files) {
    const mod = await import(pathToFileURL(path.join(root, demo, 'data', 'en', file)).href);
    for (const list of Object.values(mod)) events = events.concat(list);
  }

  // Group by category (in order of first appearance), oldest first within each.
  const groups = new Map();
  for (const e of events) {
    if (!groups.has(e.category)) groups.set(e.category, []);
    groups.get(e.category).push(e);
  }

  const out = [START, '    <section class="event-list">', '      <details>',
    `        <summary><h2>All ${events.length} events in this timeline</h2></summary>`];
  for (const [category, list] of groups) {
    list.sort((a, b) => sortKey(a.start) - sortKey(b.start));
    out.push(`        <h3>${escapeHtml(capitalize(category))}</h3>`, '        <ul>');
    for (const e of list) {
      const title = e.url
        ? `<a href="${escapeHtml(e.url)}">${escapeHtml(e.title)}</a>`
        : escapeHtml(e.title);
      const dates = e.end != null ? `${formatDate(e.start)} – ${formatDate(e.end)}` : formatDate(e.start);
      const desc = e.description ? ` ${escapeHtml(e.description)}` : '';
      out.push(`          <li><strong>${title}</strong> <span class="dates">(${dates})</span>${desc}</li>`);
    }
    out.push('        </ul>');
  }
  out.push('      </details>', '    </section>', `    ${END}`);
  const block = out.join('\n');

  let next;
  if (html.includes(START)) {
    const from = html.indexOf(START);
    const to = html.indexOf(END, from) + END.length;
    next = html.slice(0, from) + block + html.slice(to);
  } else {
    // First run: insert right after the timeline container.
    const anchor = '<div id="timeline"></div>\n';
    if (!html.includes(anchor)) throw new Error(`${demo}: no #timeline container found`);
    next = html.replace(anchor, `${anchor}    ${block}\n`);
  }

  if (next !== html) fs.writeFileSync(pagePath, next);
  console.log(`${demo}: ${events.length} events in ${groups.size} categories${next === html ? ' (unchanged)' : ''}`);
}

for (const demo of ['philosophers-in-history', 'rationalism-vs-empiricism']) await build(demo);
